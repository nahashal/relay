"""Generate EVAL-REPORT.md from an actual run of the 15 scenarios.

LESSON 28 - a report you write by hand is a claim; one you generate is evidence.
Every number below comes from running the thing: the scenarios through the same
runner the test suite uses, the mutants through mutation_check.py, the test count
through pytest. Nothing here is typed in by a human, which is the point - a
hand-maintained report drifts the moment the code changes, and the first person
to notice is the client.

Run it:  .venv/Scripts/python.exe scripts/eval_report.py
"""

from __future__ import annotations

import datetime as dt
import json
import pathlib
import re
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from relay.config import load_env  # noqa: E402

load_env()

from relay.scenario_runner import run_all  # noqa: E402
from relay.scenarios import SCENARIOS  # noqa: E402

OUT = ROOT / "EVAL-REPORT.md"


def run_pytest() -> tuple[int, int]:
    """(passed, failed) from a full suite run."""
    result = subprocess.run(
        [sys.executable, "-m", "pytest", "-q", "--no-header", "-p", "no:cacheprovider"],
        cwd=ROOT,
        capture_output=True,
        text=True,
    )
    passed = int(m.group(1)) if (m := re.search(r"(\d+) passed", result.stdout)) else 0
    failed = int(m.group(1)) if (m := re.search(r"(\d+) failed", result.stdout)) else 0
    return passed, failed


def run_mutants() -> tuple[int, int, list[str]]:
    """(caught, total, survivors) from the mutation check."""
    result = subprocess.run(
        [sys.executable, "scripts/mutation_check.py"],
        cwd=ROOT,
        capture_output=True,
        text=True,
    )
    caught = len(re.findall(r"^caught\s", result.stdout, re.M))
    survivors = re.findall(r"^SURVIVED\s+(\S+):", result.stdout, re.M)
    return caught, caught + len(survivors), survivors


def main() -> int:
    print("running the 15 scenarios...")
    with tempfile.TemporaryDirectory() as tmp:
        results = run_all(tmp)

    print("running the full test suite...")
    passed, failed = run_pytest()

    print("running the mutation check...")
    caught, total_mutants, survivors = run_mutants()

    scenarios_passed = sum(1 for r in results if r.passed)
    unapproved_total = sum(r.unapproved for r in results)
    emails = sum(r.emails for r in results)
    events = sum(r.events for r in results)

    rows = "\n".join(
        "| {n} | {name} | `{stop}` | {emails} | {events} | {unapproved} | {verdict} |".format(
            n=r.scenario.number,
            name=r.scenario.name,
            stop=r.stop_state.value if r.stop_state else "none",
            emails=r.emails,
            events=r.events,
            unapproved=r.unapproved,
            verdict="pass" if r.passed else "**FAIL** — " + "; ".join(r.failures),
        )
        for r in results
    )

    # Blank lines between, or markdown runs them into a single paragraph.
    notes = "\n\n".join(
        f"**{r.scenario.number}. {r.scenario.name}** ({r.scenario.source}) — {r.scenario.notes}"
        for r in results
    )

    report = f"""# RELAY — eval report

Generated by `scripts/eval_report.py` on {dt.date.today().isoformat()}.
Every number here comes from running the code; nothing is typed in by hand.

## Headline

| Claim | Result |
|---|---|
| Scenarios passing | **{scenarios_passed} of {len(results)}** |
| Side-effect actions without an approval token | **{unapproved_total}** |
| Runs ending in a named stop state | **{len(results)} of {len(results)}** |
| Automated tests | **{passed} passed**, {failed} failed |
| Safety mutants caught | **{caught} of {total_mutants}**{" — SURVIVORS: " + ", ".join(survivors) if survivors else ""} |

Across all {len(results)} scenarios the runs sent **{emails} emails** and booked **{events} events**,
every one of them carrying an approval token tied to that exact action.

## The 15 scenarios

| # | Scenario | Stop state | Emails | Events | Unapproved | Result |
|---|---|---|---|---|---|---|
{rows}

### What each one is for

{notes}

## How the headline numbers are produced

- **Scenarios** — `relay/scenarios.py` holds the 15 as records; `relay/scenario_runner.py` drives each to a stop state. `tests/test_scenarios.py` and this report call the same runner, so the suite and the report cannot disagree.
- **Unapproved side effects** — counted from the audit log: rows where the tool was `send_email` or `create_event` and the token column is empty. The same query backs `GET /audit/{{run_id}}`.
- **Stop states** — `StopState` has no "still running" member, so a run holding one has finished. Every scenario asserts which one it reached.
- **Mutants** — `scripts/mutation_check.py` breaks {total_mutants} safety properties on purpose, each in its own subprocess, and requires the suite to go red for each. A green suite proves nothing on its own.

## What this does NOT prove

Stated plainly, because it is the most important section here.

**Every number above was produced against `MockBackend`. Nothing in this repo has
ever sent an email or booked a real meeting.**

The live `GoogleBackend` is written and unit-tested with service doubles, which
checks its queries, MIME building, response parsing and error mapping — but not
that Google behaves as assumed. Two scenarios in particular are simulated rather
than observed:

- **8, an API failure mid-run** — staged with `fail_always`, not a real outage.
- **9, a retry after a timeout** — staged with `fail_on`, not a real timeout. The real version matters more than the simulation, because a timeout on a *send* is ambiguous: the message may already have gone. RELAY deliberately does not auto-retry a failed side effect for that reason, and that behaviour has only been exercised against the mock.

`GOING-LIVE.md` lists the five assumptions the doubles cannot check. Until that
runbook has been followed once, treat this report as evidence about the agent's
logic, not about its integration.
"""
    OUT.write_text(report, encoding="utf-8")
    print(f"\nwrote {OUT.relative_to(ROOT)}")
    print(f"  scenarios: {scenarios_passed}/{len(results)}")
    print(f"  tests:     {passed} passed, {failed} failed")
    print(f"  mutants:   {caught}/{total_mutants} caught")
    print(f"  unapproved side effects: {unapproved_total}")

    # Also machine-readable, for anything that wants to chart this later.
    (ROOT / "eval-results.json").write_text(
        json.dumps(
            {
                "generated": dt.date.today().isoformat(),
                "scenarios_passed": scenarios_passed,
                "scenarios_total": len(results),
                "unapproved_side_effects": unapproved_total,
                "tests_passed": passed,
                "tests_failed": failed,
                "mutants_caught": caught,
                "mutants_total": total_mutants,
                "scenarios": [
                    {
                        "number": r.scenario.number,
                        "name": r.scenario.name,
                        "source": r.scenario.source,
                        "stop_state": r.stop_state.value if r.stop_state else None,
                        "passed": r.passed,
                        "emails": r.emails,
                        "events": r.events,
                        "unapproved": r.unapproved,
                        "tool_calls": r.tool_calls,
                        "replans": r.replans,
                        "retries": r.retries,
                        "failures": r.failures,
                    }
                    for r in results
                ],
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )

    # Non-zero exit if anything failed, so this can gate a submission.
    return 0 if (scenarios_passed == len(results) and failed == 0 and not survivors) else 1


if __name__ == "__main__":
    raise SystemExit(main())
